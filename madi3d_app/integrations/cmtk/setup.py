def _sha256_path(path, *, max_bytes, artifact_description, cancel_check=None):
    """Hash a bounded artifact without reading it all into memory."""
    digest = hashlib.sha256()
    total = 0
    with Path(path).open("rb") as source:
        while True:
            if _cancel_requested(cancel_check):
                raise CMTKSetupCancelled(f"{artifact_description} verification was cancelled.")
            chunk = source.read(DOWNLOAD_CHUNK_SIZE)
            if not chunk:
                break
            total += len(chunk)
            if total > max_bytes:
                limit = (
                    f"{max_bytes / 1024**3:g} GiB" if max_bytes >= 1024**3
                    else f"{max_bytes / 1024**2:g} MiB"
                )
                raise CMTKUnavailableError(
                    f"The cached {artifact_description} exceeded the {limit} safety limit."
                )
            digest.update(chunk)
    return digest.hexdigest()


def _download_official_ubuntu_image(
    destination, log, *, cancel_check=None, urlopen=request.urlopen
):
    architecture = _windows_wsl_architecture()
    url, expected_sha256 = UBUNTU_WSL_IMAGES[architecture]
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(destination.name + ".part")
    if destination.exists() and not destination.is_file():
        raise CMTKUnavailableError(
            f"The Ubuntu image cache path is not a file: {destination}"
        )

    if destination.is_file():
        log(f"Checking cached {UBUNTU_WSL_RELEASE} WSL image.")
        try:
            cached_sha256 = _sha256_path(
                destination, max_bytes=MAX_WSL_IMAGE_BYTES,
                artifact_description="Ubuntu WSL image", cancel_check=cancel_check
            )
        except CMTKSetupCancelled:
            raise
        except Exception as exc:
            log(f"Cached Ubuntu image could not be verified and will be replaced: {exc}")
            destination.unlink(missing_ok=True)
        else:
            if cached_sha256.lower() == expected_sha256.lower():
                log(f"Using cached verified Ubuntu WSL image: {destination}")
                log(f"Verified Ubuntu WSL image SHA-256: {cached_sha256}")
                return destination
            log("Cached Ubuntu image failed SHA-256 verification and was discarded.")
            destination.unlink(missing_ok=True)

    temporary.unlink(missing_ok=True)
    log(f"Downloading official {UBUNTU_WSL_RELEASE} WSL image for {architecture}.")
    log(url)
    digest = hashlib.sha256()
    downloaded = 0
    next_report = 32 * 1024 * 1024
    http_request = request.Request(url, headers={"User-Agent": "MADI3D-CMTK-setup"})

    try:
        with urlopen(http_request, timeout=60) as response, temporary.open("wb") as output:
            raw_length = response.headers.get("Content-Length", "")
            try:
                content_length = int(raw_length)
            except (TypeError, ValueError):
                content_length = 0
            if content_length > MAX_WSL_IMAGE_BYTES:
                raise CMTKUnavailableError(
                    "The official Ubuntu WSL image is unexpectedly larger than 2 GiB."
                )

            while True:
                if _cancel_requested(cancel_check):
                    raise CMTKSetupCancelled("Ubuntu WSL image download was cancelled.")
                chunk = response.read(DOWNLOAD_CHUNK_SIZE)
                if not chunk:
                    break
                downloaded += len(chunk)
                if downloaded > MAX_WSL_IMAGE_BYTES:
                    raise CMTKUnavailableError(
                        "The official Ubuntu WSL image exceeded the 2 GiB safety limit."
                    )
                output.write(chunk)
                digest.update(chunk)
                if downloaded >= next_report:
                    if content_length:
                        percent = min(100, int(downloaded * 100 / content_length))
                        log(f"Downloaded {downloaded // (1024 * 1024)} MiB ({percent}%).")
                    else:
                        log(f"Downloaded {downloaded // (1024 * 1024)} MiB.")
                    next_report += 32 * 1024 * 1024
    except (CMTKSetupCancelled, CMTKUnavailableError):
        temporary.unlink(missing_ok=True)
        raise
    except Exception as exc:
        temporary.unlink(missing_ok=True)
        raise CMTKUnavailableError(
            f"The official Ubuntu WSL image could not be downloaded: {exc}"
        ) from exc

    actual_sha256 = digest.hexdigest()
    if actual_sha256.lower() != expected_sha256.lower():
        temporary.unlink(missing_ok=True)
        raise CMTKUnavailableError(
            "The downloaded Ubuntu WSL image failed SHA-256 verification. "
            "The file was discarded and was not imported."
        )
    os.replace(temporary, destination)
    log(f"Verified Ubuntu WSL image SHA-256: {actual_sha256}")
    return destination


def _perform_distro_import(
    manager, image_path, target, install_path, log, *, cancel_check=None
):
    """Register a verified root filesystem under MADI3D's reserved distro name."""
    install_path = Path(install_path)
    install_path.parent.mkdir(parents=True, exist_ok=True)
    if install_path.exists():
        if not install_path.is_dir() or any(install_path.iterdir()):
            raise CMTKUnavailableError(
                f"The managed WSL storage folder already contains data: {install_path}\n"
                "MADI3D will not overwrite it. Remove that leftover folder or choose an "
                "existing CMTK installation."
            )
    else:
        install_path.mkdir()

    feature = _WSLFeatureCapture()
    try:
        _run_command(
            manager,
            [
                "wsl.exe", "--import", target, str(install_path),
                str(Path(image_path)), "--version", "2",
            ],
            log,
            timeout=1200,
            description=f"Isolated WSL distribution import ({target})",
            cancel_check=cancel_check,
            allow_terminate=True,
            output_observer=feature,
        )
    except CMTKUnavailableError as exc:
        if not _distro_is_installed(manager, target):
            shutil.rmtree(install_path, ignore_errors=True)
        if feature.matched or _is_wsl2_feature_error(exc):
            raise _WSL2FeatureUnavailable(str(exc)) from exc
        raise
    except Exception:
        if not _distro_is_installed(manager, target):
            shutil.rmtree(install_path, ignore_errors=True)
        raise

    if not _distro_is_installed(manager, target):
        shutil.rmtree(install_path, ignore_errors=True)
        raise CMTKUnavailableError(
            f"Windows returned from the WSL import command, but distribution '{target}' "
            "was not registered."
        )
    return target


def _repair_wsl2_features(
    manager, log, stage, original_error, *, cancel_check=None
):
    config = manager.load_config()
    if config.get("wsl2_feature_repair_attempted"):
        raise CMTKUnavailableError(
            "WSL 2 still cannot create its virtual machine after Windows feature repair. "
            "Enable hardware virtualization (Intel VT-x/AMD-V/SVM) in BIOS/UEFI, ensure "
            "Virtual Machine Platform is enabled in Windows Features, and ensure the Windows "
            "hypervisor is allowed to start. Then restart Windows and retry.\n\n"
            f"Original WSL error:\n{original_error}"
        )

    stage("Enabling required WSL 2 virtualization features")
    log(
        "WSL is installed, but Windows could not create a WSL 2 virtual machine. "
        "MADI3D will ask Windows to enable the required components without installing "
        "or modifying any Linux distribution."
    )
    manager.update_config(setup_mode="auto", setup_pending=True)
    _run_elevated_wsl_install(
        manager,
        ["--install", "--no-distribution"],
        log,
        timeout=1200,
        cancel_check=cancel_check,
    )
    manager.update_config(
        setup_mode="auto",
        setup_pending=True,
        wsl2_feature_repair_attempted=True,
    )
    raise CMTKSetupPending(
        "Windows enabled or repaired the WSL 2 virtualization components. Restart Windows, "
        "then retry the CMTK action; MADI3D will resume automatically and reuse the verified "
        "Ubuntu download. If WSL 2 still cannot start after the restart, enable hardware "
        "virtualization (Intel VT-x/AMD-V/SVM) in BIOS/UEFI."
    )


def _install_managed_distribution(manager, log, stage, cancel_check=None):
    """Create/use a MADI-owned WSL distro without changing a personal Ubuntu distro."""
    config = manager.load_config()

    configured = str(config.get("distro") or "")
    configured_managed = bool(config.get("managed_distro"))
    setup_pending = bool(config.get("setup_pending"))

    # Earlier draft builds could incorrectly record the generic "Ubuntu" distro
    # as managed. Never honour that unsafe state, even when setup_pending is set.
    if (
        configured_managed
        and configured
        and configured.lower() != MANAGED_WSL_DISTRO.lower()
    ):
        log(
            f"Ignoring unsafe legacy managed-distro state for '{configured}'. "
            f"Only '{MANAGED_WSL_DISTRO}' can be managed automatically."
        )
        manager.update_config(
            managed_distro=None,
            distro=None,
            user=None,
            managed_source=None,
            managed_install_path=None,
            selection_source=None,
            cmtk_package_version=None,
        )
        configured = ""
        configured_managed = False

    if configured_managed and configured and _distro_is_installed(manager, configured):
        if setup_pending or _managed_marker_exists(manager, configured):
            log(f"Resuming MADI3D-managed WSL distribution: {configured}")
            return configured
        raise CMTKUnavailableError(
            f"MADI3D has stale ownership metadata for WSL distribution '{configured}', but the "
            "managed marker is missing. Automatic setup will not modify that distribution. "
            "Choose an existing installation explicitly or remove the stale MADI3D CMTK settings."
        )

    if _distro_is_installed(manager, MANAGED_WSL_DISTRO):
        if _managed_marker_exists(manager, MANAGED_WSL_DISTRO):
            manager.update_config(
                managed_distro=True, distro=MANAGED_WSL_DISTRO, user="root"
            )
            log(f"Using existing MADI3D-managed WSL distribution: {MANAGED_WSL_DISTRO}")
            return MANAGED_WSL_DISTRO
        raise CMTKUnavailableError(
            f"A WSL distribution named '{MANAGED_WSL_DISTRO}' already exists, but MADI3D cannot "
            "verify that it owns that environment. Automatic setup will not modify it. Rename/remove "
            "that distribution or choose 'Use an existing CMTK installation'."
        )

    target = MANAGED_WSL_DISTRO
    source = UBUNTU_WSL_RELEASE
    storage_root = _managed_storage_root(manager)
    install_path = storage_root / "WSL" / target
    download_root = storage_root / "Downloads"
    download_root.mkdir(parents=True, exist_ok=True)
    image_path = _ubuntu_image_cache_path(manager)

    manager.update_config(
        setup_mode="auto",
        setup_pending=True,
        managed_distro=True,
        distro=target,
        user="root",
        managed_source=source,
        managed_install_path=str(install_path),
    )
    try:
        stage(f"Downloading {source} for isolated CMTK setup")
        image_path = _download_official_ubuntu_image(
            image_path,
            log,
            cancel_check=cancel_check,
        )
        stage("Importing isolated Ubuntu environment for CMTK")
        log(
            f"Importing the verified image as WSL distribution '{target}'. "
            "Existing WSL distributions are not modified."
        )
        try:
            distro = _perform_distro_import(
                manager,
                image_path,
                target,
                install_path,
                log,
                cancel_check=cancel_check,
            )
        except _WSL2FeatureUnavailable as exc:
            _repair_wsl2_features(
                manager,
                log,
                stage,
                exc,
                cancel_check=cancel_check,
            )
        _remove_cached_ubuntu_image(manager, log)
        manager.update_config(wsl2_feature_repair_attempted=None)
        return distro
    except Exception:
        if not _distro_is_installed(manager, target):
            manager.update_config(
                managed_distro=None,
                distro=None,
                user=None,
                managed_source=None,
                managed_install_path=None,
            )
        raise


def _install_wsl_if_missing(manager, log, stage, cancel_check=None):
    """Install WSL components without installing or claiming a default distribution."""
    stage("Installing Windows Subsystem for Linux")
    log(
        "WSL is not currently ready. MADI3D will enable/install WSL without "
        "installing a default Linux distribution."
    )
    # Persist resumable state before making any system change. If this cannot be
    # saved, stop rather than creating an environment MADI3D cannot later identify.
    manager.update_config(setup_mode="auto", setup_pending=True)
    _run_elevated_wsl_install(
        manager,
        ["--install", "--no-distribution"],
        log,
        timeout=1200,
        cancel_check=cancel_check,
    )

    if not manager.wsl_available():
        raise CMTKSetupPending(
            "Windows installed or enabled WSL components, but WSL is not ready yet. Restart Windows. "
            "On the next CMTK action, MADI3D will resume automatic setup without asking you to choose "
            "the setup mode again."
        )


def _automatic_windows_setup(
    manager, tools, log, stage, cancel_check=None, *, reinstall=False
):
    if not manager.wsl_available():
        _install_wsl_if_missing(
            manager, log, stage, cancel_check=cancel_check
        )

    version = host_wsl_version(manager.runner)
    log(f"Host WSL runtime: {version or 'version undetermined; continuing setup'}")
    if version in ("2.4.12", "2.4.12.0"):
        log("Warning: " + wsl_runtime_guidance(version))

    distro = _install_managed_distribution(
        manager, log, stage, cancel_check=cancel_check
    )

    stage(f"Preparing {distro}")
    log("Initializing the isolated WSL distribution non-interactively as root.")
    _run_command(
        manager,
        ["wsl.exe", "-d", distro, "-u", "root", "--exec", "sh", "-lc", "printf MADI3D_WSL_READY"],
        log,
        timeout=300,
        description="WSL initialization",
        cancel_check=cancel_check,
        allow_terminate=True,
    )
    _run_command(
        manager,
        [
            "wsl.exe", "-d", distro, "-u", "root", "--exec", "sh", "-lc",
            f"printf '%s\\n' 'MADI3D managed CMTK backend' > {MANAGED_MARKER}",
        ],
        log,
        timeout=60,
        description="Marking managed WSL environment",
        cancel_check=cancel_check,
        allow_terminate=True,
    )

    stage("Waiting for Ubuntu initialization")
    _run_command(
        manager,
        [
            "wsl.exe", "-d", distro, "-u", "root", "--exec", "sh", "-lc",
            "if command -v cloud-init >/dev/null 2>&1; then "
            "cloud-init status --wait || echo 'cloud-init finished with a non-zero status'; fi",
        ],
        log,
        timeout=900,
        description="Ubuntu first-boot initialization",
        cancel_check=cancel_check,
        allow_terminate=True,
    )

    stage("Checking Ubuntu package state")
    _run_command(
        manager,
        [
            "wsl.exe", "-d", distro, "-u", "root", "--exec",
            "env", "DEBIAN_FRONTEND=noninteractive", "dpkg", "--configure", "-a",
        ],
        log,
        timeout=1200,
        description="dpkg recovery/configuration",
        cancel_check=cancel_check,
        allow_terminate=False,
    )

    stage("Updating Ubuntu package information")
    _run_command(
        manager,
        ["wsl.exe", "-d", distro, "-u", "root", "--exec", "apt-get", "-o", "DPkg::Lock::Timeout=300", "update"],
        log,
        timeout=1200,
        description="apt-get update",
        cancel_check=cancel_check,
        allow_terminate=True,
    )

    stage("Reinstalling CMTK" if reinstall else "Installing CMTK")
    log(
        ("Reinstalling" if reinstall else "Installing")
        + " the Ubuntu CMTK package in the isolated MADI3D environment."
    )
    apt_command = [
        "wsl.exe", "-d", distro, "-u", "root", "--exec",
        "env", "DEBIAN_FRONTEND=noninteractive", "LC_ALL=C",
        "apt-get", "-o", "DPkg::Lock::Timeout=300",
    ]
    install_args = ["install", "-y"]
    if reinstall:
        install_args.append("--reinstall")
    install_args.append("cmtk")
    for attempt in range(2):
        try:
            _run_command(
                manager,
                [*apt_command, *install_args],
                log,
                timeout=1800,
                description="CMTK package installation",
                cancel_check=cancel_check,
                allow_terminate=False,
            )
        except CMTKUnavailableError as exc:
            if attempt or "unmet dependencies" not in str(exc).lower():
                raise
        else:
            break

        stage("Repairing Ubuntu package dependencies")
        _run_command(
            manager,
            [*apt_command, "--fix-broken", "--no-remove", "install", "-y"],
            log,
            timeout=1800,
            description="APT dependency repair",
            cancel_check=cancel_check,
            allow_terminate=False,
        )
        stage("Retrying CMTK package installation")

    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    version_proc = manager.capture(
        [
            "wsl.exe", "-d", distro, "-u", "root", "--exec",
            "dpkg-query", "-W", "-f=${Version}", "cmtk",
        ],
        timeout=30,
    )
    if version_proc is not None and getattr(version_proc, "returncode", 1) == 0:
        version = decode_console(getattr(version_proc, "stdout", b"")).strip()
        if version:
            log(f"Installed Ubuntu CMTK package version: {version}")
            manager.update_config(cmtk_package_version=version)

    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    stage("Validating CMTK tools")
    backend = WSLCMTKBackend(distro, runner=manager.runner, user="root")
    manager.update_config(managed_distro=True, distro=distro, user="root")
    if manager.validate_backend(backend, tools, managed=True) is None:
        raise CMTKUnavailableError(
            "CMTK installation completed, but one or more required CMTK tools failed validation.\n\n"
            + manager.last_status.diagnostic_text()
        )
    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    log("CMTK validation passed: " + ", ".join(tools))
    _remove_cached_ubuntu_image(manager, log)
    return backend


def _macos_archive_cache_path(manager):
    return _managed_storage_root(manager) / "Downloads" / CMTK_MACOS_ARCHIVE_NAME


def _macos_install_root(manager):
    """MADI3D-owned CMTK prefix. Deliberately inside MADI3D's own storage, not
    /usr/local: the archive is relocatable, so nothing needs administrator rights,
    and MADI3D never modifies a system location it does not own."""
    return _managed_storage_root(manager) / f"macos-{_macos_architecture()}"


def _macos_launcher_path(manager):
    return _macos_install_root(manager) / CMTK_MACOS_LAUNCHER_RELPATH


def _download_verified_macos_archive(
    destination, log, *, cancel_check=None, urlopen=request.urlopen
):
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(destination.name + ".part")
    temporary.unlink(missing_ok=True)
    if destination.exists() and not destination.is_file():
        raise CMTKUnavailableError(
            f"The CMTK archive cache path is not a file: {destination}"
        )

    if destination.is_file():
        log("Checking cached CMTK archive.")
        try:
            cached_sha256 = _sha256_path(
                destination, max_bytes=MAX_MACOS_ARCHIVE_BYTES,
                artifact_description="CMTK archive", cancel_check=cancel_check,
            )
        except CMTKSetupCancelled:
            raise
        except Exception as exc:
            log(f"Cached CMTK archive could not be verified and will be replaced: {exc}")
            destination.unlink(missing_ok=True)
        else:
            if cached_sha256.lower() == CMTK_MACOS_ARM64_ARCHIVE_SHA256.lower():
                log(f"Using cached verified CMTK archive: {destination}")
                log(f"Verified CMTK archive SHA-256: {cached_sha256}")
                return destination
            log("Cached CMTK archive failed SHA-256 verification and was discarded.")
            destination.unlink(missing_ok=True)

    log(f"Downloading {CMTK_MACOS_ARCHIVE_NAME}.")
    log(CMTK_MACOS_ARM64_ARCHIVE_URL)
    digest = hashlib.sha256()
    downloaded = 0
    next_report = 16 * 1024 * 1024
    http_request = request.Request(
        CMTK_MACOS_ARM64_ARCHIVE_URL, headers={"User-Agent": "MADI3D-CMTK-setup"}
    )

    try:
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK archive download was cancelled.")
        with urlopen(http_request, timeout=60) as response, temporary.open("wb") as output:
            raw_length = response.headers.get("Content-Length", "")
            try:
                content_length = int(raw_length)
            except (TypeError, ValueError):
                content_length = 0
            if content_length > MAX_MACOS_ARCHIVE_BYTES:
                raise CMTKUnavailableError(
                    "The CMTK archive is unexpectedly large."
                )

            while True:
                if _cancel_requested(cancel_check):
                    raise CMTKSetupCancelled("CMTK archive download was cancelled.")
                chunk = response.read(DOWNLOAD_CHUNK_SIZE)
                if not chunk:
                    break
                downloaded += len(chunk)
                if downloaded > MAX_MACOS_ARCHIVE_BYTES:
                    raise CMTKUnavailableError(
                        "The CMTK archive exceeded the safety size limit."
                    )
                output.write(chunk)
                digest.update(chunk)
                if downloaded >= next_report:
                    if content_length:
                        percent = min(100, int(downloaded * 100 / content_length))
                        log(f"Downloaded {downloaded // (1024 * 1024)} MiB ({percent}%).")
                    else:
                        log(f"Downloaded {downloaded // (1024 * 1024)} MiB.")
                    next_report += 16 * 1024 * 1024
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK archive download was cancelled.")
        actual_sha256 = digest.hexdigest()
        if actual_sha256.lower() != CMTK_MACOS_ARM64_ARCHIVE_SHA256.lower():
            raise CMTKUnavailableError(
                "The downloaded CMTK archive failed SHA-256 verification. The file was "
                "discarded and was not extracted. If the upstream build has changed, "
                "MADI3D needs an updated, verified checksum before it can install it."
            )
        os.replace(temporary, destination)
    except (CMTKSetupCancelled, CMTKUnavailableError):
        temporary.unlink(missing_ok=True)
        raise
    except Exception as exc:
        temporary.unlink(missing_ok=True)
        raise CMTKUnavailableError(
            f"The CMTK archive could not be downloaded: {exc}"
        ) from exc

    log(f"Verified CMTK archive SHA-256: {actual_sha256}")
    return destination


def _safe_macos_archive_members(archive):
    """Reject anything that is not a plain file/directory under the expected prefix.

    The archive's SHA-256 is verified before this runs, so this is defence in depth
    rather than the primary control: it keeps a future upstream rebuild from silently
    introducing symlinks, device nodes, absolute paths or parent traversal into a
    tree MADI3D extracts.
    """
    prefix = CMTK_MACOS_ARCHIVE_PREFIX
    for member in archive.getmembers():
        name = member.name
        if not (name == prefix or name.startswith(prefix + "/")):
            raise CMTKUnavailableError(
                f"The CMTK archive contains an unexpected top-level entry: {name!r}"
            )
        if name.startswith("/") or ".." in Path(name).parts:
            raise CMTKUnavailableError(
                f"The CMTK archive contains an unsafe path: {name!r}"
            )
        if not (member.isfile() or member.isdir()):
            raise CMTKUnavailableError(
                f"The CMTK archive contains an unsupported entry type: {name!r}"
            )
        yield member


def _extract_macos_archive(
    archive_path, install_root, log, *, cancel_check=None, required_tools=CMTK_CORE_TOOLS
):
    """Prepare a complete staged tree; the caller owns publication and rollback."""
    install_root = Path(install_root)
    staging = install_root.with_name(install_root.name + ".incomplete")
    if staging.exists():
        shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)

    log(f"Extracting CMTK into {install_root}")
    try:
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK archive extraction was cancelled.")
        with tarfile.open(archive_path, "r:gz") as archive:
            members = _safe_macos_archive_members(archive)
            # The data filter additionally strips setuid/setgid/sticky bits and
            # rejects links escaping the destination. It exists on Python 3.12+ and
            # in the backports to 3.8.17/3.9.17/3.10.12/3.11.4; the explicit member
            # validation above is what carries the guarantee on older interpreters.
            if hasattr(tarfile, "data_filter"):
                archive.extractall(staging, members=members, filter="data")
            else:  # pragma: no cover - only on interpreters predating the backport
                archive.extractall(staging, members=members)
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK archive extraction was cancelled.")
        required = [CMTK_MACOS_UPSTREAM_LAUNCHER_RELPATH]
        tools = tuple(dict.fromkeys((*CMTK_CORE_TOOLS, *required_tools)))
        required.extend(f"usr/local/lib/cmtk/bin/{tool}" for tool in tools)
        missing = [name for name in required if not (staging / name).is_file()]
        if missing:
            raise CMTKUnavailableError(
                "The CMTK archive is missing required files: " + ", ".join(missing)
            )
        launcher = staging / CMTK_MACOS_LAUNCHER_RELPATH
        launcher.write_text(CMTK_MACOS_LAUNCHER_SHIM, encoding="utf-8", newline="\n")
        launcher.chmod(0o755)
        for path in (staging / "usr/local/lib/cmtk/bin").iterdir():
            if path.is_file():
                path.chmod((path.stat().st_mode & 0o777) | 0o755)
        return launcher
    except (CMTKSetupCancelled, CMTKUnavailableError):
        shutil.rmtree(staging, ignore_errors=True)
        raise
    except Exception as exc:
        shutil.rmtree(staging, ignore_errors=True)
        raise CMTKUnavailableError(f"The CMTK archive could not be extracted: {exc}") from exc


def _automatic_macos_setup(
    manager, tools, log, stage, cancel_check=None, *, reinstall=False
):
    unavailable_reason = _macos_setup_unavailable_reason(manager)
    if unavailable_reason:
        raise CMTKUnavailableError(
            unavailable_reason + " Use an existing CMTK installation instead."
        )

    architecture = _macos_architecture()
    install_root = _macos_install_root(manager)
    launcher = _macos_launcher_path(manager)
    staging = install_root.with_name(install_root.name + ".incomplete")
    backup = install_root.with_name(install_root.name + ".previous")
    if backup.exists():
        raise CMTKUnavailableError(
            f"A previous CMTK installation is retained at {backup}. "
            "Move it to a safe location before retrying setup."
        )
    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    tools = tuple(dict.fromkeys((*CMTK_CORE_TOOLS, *tools)))
    replacing = reinstall or not launcher.is_file()

    if launcher.is_file() and not reinstall:
        log(f"Using the CMTK installation MADI3D already extracted at {install_root}")
    else:
        stage(f"Downloading CMTK for macOS ({architecture})")
        archive_path = _download_verified_macos_archive(
            _macos_archive_cache_path(manager), log, cancel_check=cancel_check
        )

        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK setup was cancelled.")

        stage("Reinstalling CMTK" if reinstall else "Installing CMTK")
        log(
            "CMTK is installed inside MADI3D's own storage and needs no administrator "
            "rights; no system location is modified."
        )
        _extract_macos_archive(
            archive_path, install_root, log, cancel_check=cancel_check,
            required_tools=tools,
        )

    previous_config = manager.load_config()
    moved_previous = published = config_changed = validation_failed = False
    try:
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK setup was cancelled.")
        # A crash during the swap/probe must never leave unvalidated files ready.
        manager.update_config(
            readiness_state=CMTK_STATE_UNCHECKED,
            readiness_summary="CMTK setup has not completed validation.",
            managed_source=CMTK_MACOS_ARM64_ARCHIVE_URL,
            managed_install_path=str(install_root),
        )
        config_changed = True
        manager.invalidate()
        if replacing:
            if install_root.exists():
                atomic_replace(install_root, backup)
                moved_previous = True
            atomic_replace(staging, install_root)
            published = True
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK setup was cancelled.")
        stage("Validating CMTK tools")
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK validation was cancelled.")
        candidate = NativeCMTKBackend(runner=manager.runner, cmtk_command=str(launcher))
        ok, details = candidate.probe(tools)
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK validation was cancelled.")
        if not ok:
            validation_failed = True
            raise CMTKUnavailableError(
                "CMTK installation failed validation.\n\n" + "\n".join(details)
            )
        backend = manager.accept_backend(candidate, tools, details, managed=True)
        if _cancel_requested(cancel_check):
            raise CMTKSetupCancelled("CMTK validation was cancelled.")
    except Exception as exc:
        try:
            if published:
                shutil.rmtree(install_root)
            if moved_previous:
                atomic_replace(backup, install_root)
            if config_changed:
                manager._require_config_write(previous_config)
                manager.invalidate()
                if validation_failed and not replacing:
                    manager.mark_unavailable("The managed CMTK installation failed validation.", details)
                else:
                    manager.restore_persisted_backend()
        except Exception as rollback_error:
            manager.mark_unavailable("CMTK setup could not restore the previous installation.")
            raise CMTKUnavailableError(
                f"{exc}\n\nRestoring the previous CMTK installation failed: "
                f"{rollback_error}. Retained installation, if present: {backup}"
            ) from exc
        raise
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
    if moved_previous:
        try:
            shutil.rmtree(backup)
        except OSError as exc:
            log(f"WARNING: Could not remove the previous CMTK installation at {backup}: {exc}")
    log("CMTK validation passed: " + ", ".join(tools))
    try:
        _macos_archive_cache_path(manager).unlink(missing_ok=True)
        log("Removed the downloaded archive after successful setup.")
    except Exception as exc:
        log(f"WARNING: Could not remove the downloaded archive: {exc}")
    return backend


def _linux_distribution_id():
    try:
        for line in Path("/etc/os-release").read_text(
            encoding="utf-8", errors="replace"
        ).splitlines():
            if line.startswith("ID="):
                return line.split("=", 1)[1].strip().strip('"').lower()
    except Exception:
        pass
    return ""


def _system_executable_available(path):
    return Path(path).is_file() and os.access(path, os.X_OK)


def _native_setup_unavailable_reason(manager):
    if manager.platform_name() != "linux":
        return "Automatic native package installation is available only on Linux."

    distro = _linux_distribution_id()
    if distro not in ("ubuntu", "debian"):
        label = distro or "unknown Linux distribution"
        return (
            "Automatic CMTK installation is supported only on native Ubuntu/Debian; "
            f"this system reports {label}."
        )

    required = (
        (NATIVE_APT_GET, "apt-get"),
        (NATIVE_APT_CACHE, "apt-cache"),
        (NATIVE_ENV, "env"),
    )
    missing = [
        label
        for path, label in required
        if not _system_executable_available(path)
    ]
    if missing:
        return (
            "Required system package tools are unavailable: "
            + ", ".join(missing)
            + "."
        )

    running_as_root = hasattr(os, "geteuid") and os.geteuid() == 0
    if not running_as_root and not _system_executable_available(NATIVE_PKEXEC):
        return (
            "Graphical administrator elevation (pkexec) is unavailable. "
            "Install the cmtk package manually."
        )
    return ""


def _automatic_native_setup(
    manager, tools, log, stage, cancel_check=None, *, reinstall=False
):
    unavailable_reason = _native_setup_unavailable_reason(manager)
    if unavailable_reason:
        raise CMTKUnavailableError(
            unavailable_reason + " Use an existing CMTK installation instead."
        )

    log(
        "Native Linux automatic setup installs the distribution's system "
        "CMTK package."
    )
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        prefix = []
    else:
        prefix = [NATIVE_PKEXEC]

    stage("Updating package information")
    _run_command(
        manager,
        prefix + [
            NATIVE_ENV,
            "LC_ALL=C",
            NATIVE_APT_GET,
            "-o",
            "DPkg::Lock::Timeout=300",
            "update",
        ],
        log,
        timeout=1200,
        description="apt-get update",
        cancel_check=cancel_check,
        allow_terminate=False,
    )
    stage("Checking CMTK package availability")
    candidate = _AptPolicyCapture()
    _run_command(
        manager,
        [NATIVE_ENV, "LC_ALL=C", NATIVE_APT_CACHE, "policy", "cmtk"],
        log,
        timeout=60,
        description="CMTK package availability check",
        cancel_check=cancel_check,
        allow_terminate=True,
        output_observer=candidate,
    )
    candidate.finish_line()
    if not candidate.has_candidate:
        raise CMTKUnavailableError(
            "The cmtk package has no installation candidate in the configured repositories. "
            "On Ubuntu, enable the official Universe repository and retry, or choose an "
            "existing CMTK installation. MADI3D did not change repository configuration."
        )
    stage("Reinstalling CMTK" if reinstall else "Installing CMTK")
    install_args = [
        NATIVE_ENV, "LC_ALL=C", "DEBIAN_FRONTEND=noninteractive",
        NATIVE_APT_GET, "-o", "DPkg::Lock::Timeout=300",
        "install", "-y",
    ]
    if reinstall:
        install_args.append("--reinstall")
    install_args.append("cmtk")
    _run_command(
        manager,
        prefix + install_args,
        log,
        timeout=1800,
        description="CMTK package installation",
        cancel_check=cancel_check,
        allow_terminate=False,
    )
    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    stage("Validating CMTK tools")
    manager.invalidate()
    backend = manager.detect(tools)
    if backend is None:
        raise CMTKUnavailableError(
            "CMTK installation completed but validation still failed.\n\n"
            + manager.last_status.diagnostic_text()
        )
    if _cancel_requested(cancel_check):
        raise CMTKSetupCancelled("CMTK setup was cancelled.")
    log("CMTK validation passed: " + ", ".join(tools))
    return backend


def _create_setup_session(manager, tools, *, force_setup=False):
    """Construct the private QtCore owner only for interactive setup."""
    from PySide6 import QtCore

    class Worker(QtCore.QObject):
        stage = QtCore.Signal(str)
        completed = QtCore.Signal(object)
        not_found = QtCore.Signal()
        failed = QtCore.Signal(str)
        restart_required = QtCore.Signal(str)
        cancelled = QtCore.Signal(str)

        def __init__(self, mode, cancel_check, log, candidate=None, reinstall=False):
            super().__init__()
            self.mode = str(mode)
            self.cancel_check = cancel_check
            self.log = log
            self.candidate = candidate
            self.reinstall = bool(reinstall)

        def run(self):
            try:
                if self.mode == "detect":
                    self.stage.emit("Checking for an existing CMTK installation")
                    backend = manager.detect(tools)
                    if _cancel_requested(self.cancel_check):
                        raise CMTKSetupCancelled("CMTK check was cancelled.")
                    if backend is None:
                        self.not_found.emit()
                        return
                elif self.mode == "existing":
                    self.stage.emit("Validating the selected CMTK installation")
                    if getattr(self.candidate, "kind", "") == "wsl":
                        version = host_wsl_version(manager.runner)
                        self.log(wsl_runtime_guidance(version))
                    backend = manager.validate_backend(
                        self.candidate, tools, managed=False
                    )
                    if _cancel_requested(self.cancel_check):
                        raise CMTKSetupCancelled("CMTK validation was cancelled.")
                    if backend is None:
                        raise CMTKUnavailableError(
                            "The selected installation could not run all required "
                            "CMTK tools.\n\n"
                            + manager.last_status.diagnostic_text()
                        )
                elif manager.platform_name() == "windows":
                    backend = _automatic_windows_setup(
                        manager,
                        tools,
                        self.log,
                        self.stage.emit,
                        cancel_check=self.cancel_check,
                        reinstall=self.reinstall,
                    )
                elif manager.platform_name() == "macos":
                    backend = _automatic_macos_setup(
                        manager,
                        tools,
                        self.log,
                        self.stage.emit,
                        cancel_check=self.cancel_check,
                        reinstall=self.reinstall,
                    )
                else:
                    backend = _automatic_native_setup(
                        manager,
                        tools,
                        self.log,
                        self.stage.emit,
                        cancel_check=self.cancel_check,
                        reinstall=self.reinstall,
                    )
            except CMTKSetupPending as exc:
                self.restart_required.emit(str(exc))
            except CMTKSetupCancelled as exc:
                self.cancelled.emit(str(exc) or "CMTK setup was cancelled.")
            except Exception as exc:
                self.failed.emit(str(exc))
            else:
                self.completed.emit(backend)

    class SetupSession(QtCore.QObject):
        """Own one interactive setup attempt and reduce results after retirement."""

        changed = QtCore.Signal()
        run_started = QtCore.Signal(bool)
        stage = QtCore.Signal(str)
        log = QtCore.Signal(str)
        error = QtCore.Signal(str)
        existing_requested = QtCore.Signal()
        accepted = QtCore.Signal()
        dismissed = QtCore.Signal()
        retired = QtCore.Signal()

        def __init__(self):
            super().__init__()
            self.backend = None
            self.restart_message = ""
            self.running = False
            self._thread = None
            self._worker = None
            self._pending_log = _SetupLogTail()
            self._log_timer = QtCore.QTimer(self)
            self._log_timer.setInterval(50)
            self._log_timer.timeout.connect(self._flush_log)
            self._active_mode = ""
            self._terminal_kind = None
            self._terminal_payload = None
            self._cancel_requested_flag = False
            self.force_setup = bool(force_setup)
            self.phase = "choices" if self.force_setup else "running"
            config = manager.load_config()
            self._reinstall_requested = bool(
                self.force_setup
                and (config.get("last_successful_validation") or config.get("cmtk_package_version"))
            )
            self._resume_auto = bool(
                config.get("setup_mode") == "auto" and config.get("setup_pending")
            )
            self.platform_name = manager.platform_name()
            self.unavailable_reason = (
                _native_setup_unavailable_reason(manager) if self.platform_name == "linux"
                else _macos_setup_unavailable_reason(manager) if self.platform_name == "macos"
                else ""
            )
            status = manager.persisted_status() if self.force_setup else manager.last_status
            self.status_text = status.diagnostic_text()
            self.default_native_path = {
                "linux": "/usr/bin/cmtk", "macos": "/usr/local/bin/cmtk"
            }.get(self.platform_name, "")

        def existing_distros(self):
            distros = manager.list_wsl_distros()
            if not distros:
                raise CMTKUnavailableError(
                    "WSL is installed but no Linux distribution exists yet. "
                    "Choose Automatic setup to install an isolated Ubuntu environment."
                )
            return manager.rank_distros(distros)

        def select_existing(self, selection):
            if self.running or not selection:
                return
            try:
                if self.platform_name == "windows":
                    candidate = WSLCMTKBackend(str(selection), runner=manager.runner)
                else:
                    candidate = NativeCMTKBackend(runner=manager.runner, cmtk_command=str(selection))
            except Exception as exc:
                self.error.emit(str(exc))
                return
            self._start_worker("existing", candidate=candidate, clear_log=True)

        def continue_requested(self, mode):
            if self.running:
                return
            if self.restart_message:
                self.dismissed.emit()
            elif self.backend is not None:
                self.accepted.emit()
            elif self.phase != "choices":
                self.phase = "choices"
                self.changed.emit()
            elif mode == "existing":
                self.existing_requested.emit()
            else:
                self.start_automatic(clear_log=True)

        def dismiss_requested(self):
            if not self.running:
                self.dismissed.emit()
                return
            if self._cancel_requested_flag:
                return
            self._cancel_requested_flag = True
            self.changed.emit()
            if self._active_mode == "automatic" and self.platform_name in ("windows", "linux"):
                self.stage.emit("Stopping safely; an installation step may need to finish...")
                message = "MADI3D will let an active system installation step finish safely."
            elif self._active_mode == "automatic":
                self.stage.emit("Stopping CMTK setup safely...")
                message = (
                    "MADI3D will finish the current step safely and retain the previous "
                    "installation if setup has not completed."
                )
            else:
                self.stage.emit("Stopping the CMTK check...")
                message = "MADI3D will stop after the current CMTK check finishes."
            self.log.emit("\nCancellation requested. " + message)

        def is_cancel_requested(self):
            return self._cancel_requested_flag

        def start_detection(self):
            self._start_worker("detect", clear_log=True)

        def start_automatic(self, clear_log=False):
            if self.running or self.backend is not None:
                return
            try:
                manager.update_config(
                    setup_mode="auto", setup_pending=True,
                    readiness_state="unavailable",
                    readiness_summary="CMTK setup/repair is in progress or pending.",
                )
            except Exception as exc:
                self.error.emit(str(exc))
                self.phase = "choices"
                self.changed.emit()
                return
            self._start_worker(
                "automatic", clear_log=clear_log, reinstall=self._reinstall_requested
            )

        def _start_worker(self, mode, *, candidate=None, clear_log=False, reinstall=False):
            if self.running:
                return
            self.restart_message = ""
            self._terminal_kind = None
            self._terminal_payload = None
            self._cancel_requested_flag = False
            self.running = True
            self._active_mode = str(mode)
            self.phase = "running"
            self._pending_log.take()
            self._log_timer.start()
            self.run_started.emit(clear_log)
            self.changed.emit()
            labels = {
                "detect": "Checking for an existing CMTK installation...",
                "existing": "Validating the selected CMTK installation...",
                "automatic": (
                    "Starting CMTK reinstall/repair..."
                    if reinstall else "Starting automatic CMTK setup..."
                ),
            }
            self.stage.emit(labels.get(mode, "Working..."))
            thread = QtCore.QThread(self)
            worker = Worker(
                mode, self.is_cancel_requested, self._queue_log,
                candidate=candidate, reinstall=reinstall
            )
            worker.moveToThread(thread)
            self._thread = thread
            self._worker = worker
            thread.started.connect(worker.run)
            worker.stage.connect(self._set_stage)
            worker.completed.connect(self._worker_completed)
            worker.not_found.connect(self._worker_not_found)
            worker.failed.connect(self._worker_failed)
            worker.restart_required.connect(self._worker_restart_required)
            worker.cancelled.connect(self._worker_cancelled)
            worker.completed.connect(thread.quit)
            worker.not_found.connect(thread.quit)
            worker.failed.connect(thread.quit)
            worker.restart_required.connect(thread.quit)
            worker.cancelled.connect(thread.quit)
            thread.finished.connect(worker.deleteLater)
            thread.finished.connect(self._thread_finished)
            thread.start()

        def _queue_log(self, text):
            self._pending_log.append(str(text).rstrip() + "\n")

        def _flush_log(self):
            text = self._pending_log.take()
            if text:
                self.log.emit(text)

        def _set_stage(self, text):
            self.stage.emit(text)
            self.log.emit("\n== " + text + " ==")

        def _worker_completed(self, backend):
            self._terminal_kind = self._active_mode + "_complete"
            self._terminal_payload = backend
            self.stage.emit("Finishing CMTK check...")

        def _worker_not_found(self):
            self._terminal_kind = "detect_missing"
            self._terminal_payload = None

        def _worker_failed(self, message):
            self._terminal_kind = "failed"
            self._terminal_payload = str(message)
            self.stage.emit("Finishing failed setup step...")

        def _worker_restart_required(self, message):
            self._terminal_kind = "restart"
            self._terminal_payload = str(message)
            self.stage.emit("Finishing Windows setup step...")

        def _worker_cancelled(self, message):
            self._terminal_kind = "cancelled"
            self._terminal_payload = str(message)

        def _clear_pending_after_stop(self, active_mode):
            if active_mode != "automatic":
                return
            try:
                manager.update_config(setup_pending=None, setup_mode=None)
            except Exception as exc:
                self.log.emit("\nWARNING: Could not clear pending setup state: " + str(exc))

        def _thread_finished(self):
            thread = self._thread
            # finished may be delivered while native thread cleanup is still
            # active. Retain its owner and yield to Qt until the join is ready.
            if not thread.wait(0):
                QtCore.QTimer.singleShot(1, self._thread_finished)
                return
            thread.deleteLater()
            self._log_timer.stop()
            self._flush_log()
            self.running = False
            kind = self._terminal_kind
            payload = self._terminal_payload
            active_mode = self._active_mode
            self._active_mode = ""
            self._thread = None
            self._worker = None

            if kind == "detect_complete":
                self.backend = payload
                self.accepted.emit()
            elif kind == "detect_missing":
                self.status_text = manager.last_status.diagnostic_text() or "CMTK is not configured."
                if self._resume_auto and not self.is_cancel_requested():
                    self._resume_auto = False
                    self.start_automatic(clear_log=False)
                else:
                    self.phase = "choices"
                    self.changed.emit()
            elif kind in ("automatic_complete", "existing_complete"):
                self.backend = payload
                self.phase = "ready"
                self.stage.emit("CMTK is ready")
                self.log.emit("\nSetup and validation completed successfully.")
                self.log.emit(manager.last_status.diagnostic_text())
                self.changed.emit()
            elif kind == "restart":
                self.restart_message = str(payload or "Windows restart required.")
                self.phase = "restart"
                self.stage.emit("Windows restart required")
                self.log.emit("\n" + self.restart_message)
                self.changed.emit()
            else:
                self._clear_pending_after_stop(active_mode)
                self.phase = "stopped"
                if kind == "cancelled":
                    self.stage.emit("CMTK setup cancelled")
                    self.log.emit("\n" + str(payload or "CMTK setup was cancelled."))
                else:
                    self.stage.emit("CMTK setup did not complete")
                    self.log.emit("\nERROR: " + str(payload or "CMTK setup stopped unexpectedly."))
                self.changed.emit()
            self.retired.emit()

    return SetupSession()


def _setup_dialog(manager, tools, parent=None, *, force_setup=False):
    """Compose the interactive session/view and translate the existing outcome."""
    from PySide6 import QtCore, QtWidgets
    from shiboken6 import isValid
    from madi3d_app.ui.dialogs.cmtk_setup import CMTKSetupDialog

    session = _create_setup_session(manager, tools, force_setup=force_setup)
    dialog = CMTKSetupDialog(session, parent)
    try:
        result = dialog.exec()
    finally:
        # Parent destruction or external done() can exit exec while a worker is
        # active. Keep its independent owner alive and Qt responsive until safe
        # retirement, just as the ordinary close/reject route does.
        if session.running:
            retirement_loop = QtCore.QEventLoop()
            session.retired.connect(retirement_loop.quit)
            session.dismiss_requested()
            while session.running:
                retirement_loop.exec()
        if isValid(dialog):
            dialog.deleteLater()
        session.deleteLater()
    if session.restart_message:
        raise CMTKSetupPending(session.restart_message)
    if result != QtWidgets.QDialog.DialogCode.Accepted or session.backend is None:
        raise CMTKSetupCancelled()
    return session.backend


def ensure_cmtk_ready(
    tools=(), *, parent=None, interactive=True, force_setup=False
):
    """Return CMTK without re-probing a persisted-ready backend on normal use."""
    manager = get_cmtk_manager()
    tools = tuple(dict.fromkeys(str(v) for v in tools if str(v).strip()))

    if not force_setup:
        if manager.backend is not None:
            return manager.backend
        backend = manager.restore_persisted_backend()
        if backend is not None:
            return backend

    if not interactive:
        backend = manager.detect(tools)
        if backend is None:
            raise CMTKUnavailableError(manager.last_status.diagnostic_text())
        return backend

    return _setup_dialog(
        manager, tools or CMTK_CORE_TOOLS, parent, force_setup=bool(force_setup)
    )


def install_or_reinstall_cmtk(*, parent=None, tools=CMTK_CORE_TOOLS):
    """Explicit dependency-menu entry point; always opens setup/repair UI."""
    return ensure_cmtk_ready(
        tools, parent=parent, interactive=True, force_setup=True
    )


